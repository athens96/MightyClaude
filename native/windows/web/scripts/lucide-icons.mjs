// Usage: npm pack lucide-static@1.61.0 && tar xzf lucide-static-1.61.0.tgz && node scripts/lucide-icons.mjs package
// Add a name to `names` and run it again for one more icon.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const names = [
  'search', 'layout-grid', 'folder-plus', 'globe', 'folder', 'folder-open', 'panel-left', 'moon', 'sun', 'settings', 'monitor',
  'paw-print', 'plus', 'x', 'chevron-down', 'chevron-right', 'chevron-up', 'check', 'circle-question-mark', 'asterisk', 'paperclip',
  'brain', 'shield', 'ellipsis', 'git-branch', 'git-fork', 'split', 'square', 'arrow-up', 'zoom-in', 'zoom-out', 'text-align-start',
  'workflow', 'columns-3', 'clock', 'layers', 'eye-off', 'eye', 'maximize-2', 'minimize-2', 'clipboard-list', 'square-terminal',
  'terminal', 'file', 'file-text', 'zap', 'circle-check', 'circle', 'circle-dot', 'refresh-cw', 'external-link', 'copy', 'pencil',
  'trash', 'info', 'triangle-alert', 'circle-x', 'network', 'list-checks', 'message-square', 'sparkles', 'play', 'square-pen',
  'columns-2', 'rows-2', 'clock-fading', 'list', 'share-2', 'puzzle', 'square-kanban', 'brain-circuit', 'shield-half', 'git-merge', 'arrow-down', 'panel-bottom', 'gallery-vertical-end', 'hand', 'message-circle-question-mark', 'list-todo', 'scroll-text', 'image', 'file-code', 'folder-closed', 'expand', 'shrink', 'move-diagonal-2', 'chevrons-up-down', 'arrow-up-right', 'square-arrow-out-up-right', 'dot', 'ellipsis-vertical', 'sliders-horizontal', 'circle-stop', 'circle-arrow-up', 'loader-circle', 'list-plus', 'lock-open', 'square-stack', 'layers-2', 'minus', 'clipboard-check', 'notebook-text', 'triangle',
];
const root = process.argv[2];
if (!root) throw new Error('usage: node scripts/lucide-icons.mjs <unpacked lucide-static package folder>');
const nodes = JSON.parse(readFileSync(join(root, 'icon-nodes.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const body = names.map((name) => {
  if (!nodes[name]) throw new Error('no Lucide icon ' + name);
  return '  ' + JSON.stringify(name) + ': ' + JSON.stringify(nodes[name].map(([tag, attrs]) => [tag, attrs])) + ',';
}).join('\n');
writeFileSync(new URL('../src/icons/lucide.ts', import.meta.url), `// Generated by scripts/lucide-icons.mjs from lucide-static ${version} (ISC, native/licenses/lucide-LICENSE). Do not edit.
export type IconNode = [string, Record<string, string | number>][];
export const lucide = {
${body}
} satisfies Record<string, IconNode>;
export type IconName = keyof typeof lucide;
`);
