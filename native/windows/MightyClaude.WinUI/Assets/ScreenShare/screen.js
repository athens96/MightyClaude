'use strict';
// This packaged page has no navigation, network fetch, host objects or general
// application bridge. Its sole job is native frames -> browser WebRTC.
(() => {
  const peers = new Map();
  let epoch = 0;
  const post = value => chrome.webview.postMessage(value);
  const bytes = value => new TextEncoder().encode(value).length;
  const live = p => peers.get(p.session.sessionId) === p && !p.closed;
  const emit = (p, value) => { if (live(p)) post({ type: 'signal', sessionId: p.session.sessionId, signal: value }); };
  const canvas = () => { const c = document.createElement('canvas'); c.width = 2; c.height = 2; return c; };
  function stop(id) {
    const p = peers.get(id); if (!p) return;
    peers.delete(id); p.closed = true; clearInterval(p.stats);
    p.channel.close(); p.connection.close();
    for (const stream of p.streams) for (const track of stream.getTracks()) track.stop();
    for (const surface of p.surfaces) { surface.width = surface.height = 1; surface.getContext('2d').clearRect(0, 0, 1, 1); }
  }
  function namedSdp(p, sdp) {
    for (let i = 0; i < p.streams.length; i++) {
      const actual = p.streams[i].id, name = i === 0 ? 'screen' : 'overview';
      // Stream identifiers are UUIDs generated by the browser, never phone data.
      sdp = sdp.split('a=msid:' + actual + ' ').join('a=msid:' + name + ' ');
      sdp = sdp.split(' msid:' + actual + ' ').join(' msid:' + name + ' ');
      sdp = sdp.split(' ' + actual + '\r\n').join(' ' + name + '\r\n');
    }
    return sdp;
  }
  async function offer(p, restart) {
    p.offered = false;
    const created = await p.connection.createOffer({ iceRestart: restart });
    if (!live(p)) return;
    await p.connection.setLocalDescription({ type: 'offer', sdp: namedSdp(p, created.sdp) });
    if (!live(p)) return;
    emit(p, { type: 'screen-offer', sessionId: p.session.sessionId, sdp: p.connection.localDescription.sdp,
      mode: p.session.mode, displayId: p.session.displayId, codec: 'H264', quality: p.session.quality, iceRestart: restart });
    p.offered = true;
    for (const candidate of p.localIce.splice(0)) emit(p, candidate);
  }
  async function rates(p, relay) {
    for (let i = 0; i < p.senders.length; i++) {
      const sender = p.senders[i], parameters = sender.getParameters();
      if (!parameters.encodings?.length) parameters.encodings = [{}];
      parameters.degradationPreference = 'maintain-resolution';
      parameters.encodings[0].maxBitrate = i ? 200000 : Math.min(p.session.quality.maxBitrateKbps, relay ? 2000 : 6000) * 1000;
      parameters.encodings[0].maxFramerate = i ? 2 : p.session.quality.fps;
      await sender.setParameters(parameters);
    }
  }
  async function start(session, iceServers) {
    stop(session.sessionId);
    const connection = new RTCPeerConnection({ iceServers, bundlePolicy: 'max-bundle', rtcpMuxPolicy: 'require' });
    const surfaces = [canvas(), canvas()], streams = surfaces.map(c => c.captureStream(0));
    const channel = connection.createDataChannel('screen-control', { ordered: true });
    const p = { session, connection, channel, surfaces, streams, closed: false, senders: [], localIce: [], remoteIce: [], offered: false, statsBusy: false };
    peers.set(session.sessionId, p);
    try {
      const codecs = RTCRtpSender.getCapabilities('video').codecs.filter(c => /^(video\/H264|video\/rtx|video\/red|video\/ulpfec)$/i.test(c.mimeType));
      if (!codecs.some(c => c.mimeType.toLowerCase() === 'video/h264')) throw new Error('H264 unavailable');
      for (let i = 0; i < streams.length; i++) {
        const track = streams[i].getVideoTracks()[0]; track.contentHint = 'text';
        const transceiver = connection.addTransceiver(track, { direction: 'sendonly', streams: [streams[i]] });
        transceiver.setCodecPreferences(codecs); p.senders.push(transceiver.sender);
      }
      connection.onicecandidate = e => {
        const value = { type: 'screen-ice', sessionId: session.sessionId, ...(e.candidate ? e.candidate.toJSON() : { candidate: '' }) };
        if (p.offered) emit(p, value); else p.localIce.push(value);
      };
      connection.onconnectionstatechange = () => {
        if (!live(p)) return;
        post({ type: 'state', sessionId: session.sessionId, state: connection.connectionState });
        if (connection.connectionState === 'failed') stop(session.sessionId);
      };
      channel.onmessage = e => { if (live(p) && typeof e.data === 'string' && bytes(e.data) <= 65536) post({ type: 'data', sessionId: session.sessionId, data: e.data }); };
      await offer(p, false); if (!live(p)) return;
      await rates(p, false);
      p.stats = setInterval(async () => {
        if (p.statsBusy || !live(p)) return; p.statsBusy = true;
        try {
          const stats = await connection.getStats(); let relay = false;
          stats.forEach(row => { if (row.type === 'candidate-pair' && row.state === 'succeeded' && (row.nominated || row.selected)) relay ||= stats.get(row.localCandidateId)?.candidateType === 'relay' || stats.get(row.remoteCandidateId)?.candidateType === 'relay'; });
          if (relay !== p.relay && live(p)) { p.relay = relay; await rates(p, relay); }
        } catch { /* a closing peer has no stats */ } finally { p.statsBusy = false; }
      }, 3000);
    } catch (error) { stop(session.sessionId); throw error; }
  }
  async function signal(id, message) {
    const p = peers.get(id); if (!p) return;
    if (message.type === 'screen-answer') {
      await p.connection.setRemoteDescription({ type: 'answer', sdp: message.sdp });
      for (const candidate of p.remoteIce.splice(0)) await p.connection.addIceCandidate(candidate);
    } else if (message.type === 'screen-ice') {
      const candidate = message.candidate ? { candidate: message.candidate, sdpMid: message.sdpMid ?? null, sdpMLineIndex: message.sdpMLineIndex ?? null, usernameFragment: message.usernameFragment ?? undefined } : null;
      if (!p.connection.remoteDescription) p.remoteIce.push(candidate); else await p.connection.addIceCandidate(candidate);
    } else if (message.type === 'host-ice-restart') {
      p.connection.setConfiguration({ ...p.connection.getConfiguration(), iceServers: message.iceServers }); await offer(p, true);
    }
  }
  async function draw(frame) {
    const ticket = epoch;
    const decode = data => new Promise((resolve, reject) => { const image = new Image(); image.onload = () => resolve(image); image.onerror = reject; image.src = 'data:image/jpeg;base64,' + data; });
    const images = [await decode(frame.data), frame.overviewData ? await decode(frame.overviewData) : null];
    if (ticket !== epoch) return;
    for (const p of peers.values()) {
      if (!live(p)) continue;
      for (let i = 0; i < 2; i++) {
        const image = images[i]; if (!image) continue;
        const scale = Math.min(1, (i ? 640 : p.session.quality.width) / image.width, (i ? 360 : p.session.quality.height) / image.height);
        const width = Math.max(2, Math.floor(image.width * scale / 2) * 2), height = Math.max(2, Math.floor(image.height * scale / 2) * 2);
        const surface = p.surfaces[i]; if (surface.width !== width || surface.height !== height) { surface.width = width; surface.height = height; }
        surface.getContext('2d', { alpha: false }).drawImage(image, 0, 0, width, height);
        p.streams[i].getVideoTracks()[0].requestFrame();
      }
    }
  }
  async function sendData(id, value) {
    const p = peers.get(id), text = JSON.stringify(value);
    if (!p || !live(p) || p.channel.readyState !== 'open' || bytes(text) > 65536) throw new Error('channel unavailable');
    const deadline = performance.now() + 5000;
    while (p.channel.bufferedAmount > 131072) {
      if (!live(p) || performance.now() > deadline) throw new Error('channel busy');
      await new Promise(resolve => setTimeout(resolve, 20));
    }
    p.channel.send(text);
  }
  chrome.webview.addEventListener('message', async event => {
    const m = event.data; if (!m || typeof m.id !== 'number') return;
    try {
      switch (m.type) {
        case 'start': await start(m.session, m.iceServers); break;
        case 'signal': await signal(m.sessionId, m.signal); break;
        case 'frame': await draw(m.frame); break;
        case 'data': await sendData(m.sessionId, m.message); break;
        case 'display': for (const p of peers.values()) p.session.displayId = m.displayId; break;
        case 'stop': stop(m.sessionId); break;
        case 'halt': epoch++; for (const id of Array.from(peers.keys())) stop(id); break;
        default: throw new Error('unsupported command');
      }
      post({ type: 'ack', id: m.id, ok: true });
    } catch { post({ type: 'ack', id: m.id, ok: false }); }
  });
  post({ type: 'ready', h264: RTCRtpSender.getCapabilities('video').codecs.some(c => c.mimeType.toLowerCase() === 'video/h264') });
})();
